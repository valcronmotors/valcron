"""Rebuild the calculator-only dictionary JSON from the supplied 15-column CSV."""
import csv, hashlib, json, pathlib, gzip
root = pathlib.Path(__file__).resolve().parents[1]
source = root / 'tabla-impuestos-placa.csv'
raw = source.read_bytes()
with source.open(encoding='utf-8-sig', newline='') as f:
    reader = csv.reader(f, delimiter=';')
    header = next(reader)
    if len(header) != 15 or header[-1] != 'ImpuestoPlaca': raise ValueError('Unexpected CSV schema')
    rows = list(reader)
unique = list(dict.fromkeys(tuple(row) for row in rows))
values, maps = [[] for _ in header], [{} for _ in header]
encoded = []
for row in unique:
    if len(row) != 15: raise ValueError('Every row must contain 15 columns')
    if not 2021 <= int(row[2]) <= 2025 or float(row[14]) < 0: raise ValueError('Invalid year/tax')
    out = []
    for i, value in enumerate(row):
        if value not in maps[i]:
            maps[i][value] = len(values[i]); values[i].append(value)
        out.append(maps[i][value])
    encoded.append(out)
payload = json.dumps({'version':1,'sourceRows':len(rows),'values':values,'rows':encoded}, ensure_ascii=False, separators=(',',':')).encode()
checksum = hashlib.sha256(payload).hexdigest()[:12]
name = f'import-tax-table-{checksum}.json'
for old in (root/'public/data').glob('import-tax-table-*.json'):
    if old.name != name: old.unlink()
(root/'public/data'/name).write_bytes(payload)
(root/'src/lib/import-tax-manifest.ts').write_text(f'// Generated by scripts/build-import-tax-table.py; data is fetched only by the calculator.\nexport const IMPORT_TAX_TABLE_URL = "/data/{name}";\nexport const IMPORT_TAX_TABLE_COUNTS = {{ sourceRows: {len(rows)}, uniqueRows: {len(unique)}, duplicates: {len(rows)-len(unique)} }};\n')
print(json.dumps({'file':name,'rows':len(rows),'unique':len(unique),'bytes':len(payload),'gzipBytes':len(gzip.compress(payload))}))
